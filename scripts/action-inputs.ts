// npm run action-inputs — writes shared/action-inputs.ts from the input
// schemas in extension.json. Run it after changing an action's input schema;
// a test fails while the written file and the schemas disagree.
//
// The types say exactly what the boundary check (server/action-params.ts)
// proves of a call's parameters, and no more: a required parameter is present,
// each top-level value has one of its declared types and is within its enum,
// and each item of a list has one of the item types. A nested object is typed
// `Record<string, unknown>`, because its shape is the handler's to check.

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { inputSchemas, type ParamSchema, typesOf } from '../server/input-schemas.ts'

/** Where the generated types are written. */
export const ACTION_INPUTS_FILE = fileURLToPath(new URL('../shared/action-inputs.ts', import.meta.url))

const TYPE_OF: Record<string, string> = {
  string: 'string',
  number: 'number',
  integer: 'number',
  boolean: 'boolean',
  null: 'null',
  object: 'Record<string, unknown>',
}

const literal = (value: unknown) => (typeof value === 'string' ? `'${value.replace(/[\\']/g, '\\$&')}'` : String(value))

/** The TypeScript type of a value one schema accepts, as the check reads that schema. */
function typeOf(schema: ParamSchema): string {
  if (schema.enum) {
    return schema.enum.map(literal).join(' | ')
  }
  const types = typesOf(schema).map((type) => {
    if (type !== 'array') {
      return TYPE_OF[type] ?? 'unknown'
    }
    const items = schema.items ? typesOf(schema.items).map((item) => TYPE_OF[item] ?? 'unknown') : []
    return items.length === 0 ? 'unknown[]' : items.length === 1 ? `${items[0]}[]` : `Array<${items.join(' | ')}>`
  })
  return types.length === 0 ? 'unknown' : types.join(' | ')
}

const propertyName = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : literal(name))

function inputType(schema: ParamSchema): string {
  const properties = Object.entries(schema.properties ?? {})
  if (properties.length === 0) {
    return 'Record<string, never>'
  }
  const required = new Set(schema.required ?? [])
  const lines = properties.map(
    ([name, property]) => `    ${propertyName(name)}${required.has(name) ? '' : '?'}: ${typeOf(property)}`,
  )
  return `{\n${lines.join('\n')}\n  }`
}

/** The source of shared/action-inputs.ts for `schemas`, keyed by action id. */
export function renderActionInputs(schemas: Record<string, ParamSchema>): string {
  const actions = Object.entries(schemas).map(([id, schema]) => `  ${propertyName(id)}: ${inputType(schema)}`)
  return [
    '// Generated by scripts/action-inputs.ts from the input schemas in',
    '// extension.json: run `npm run action-inputs` after changing one, never edit',
    '// this file. Each action’s parameters as the boundary check proves them.',
    '',
    '/** The parameters of each `tasks` App action, by action id. */',
    'export interface ActionInputs {',
    ...actions,
    '}',
    '',
    'export type ActionId = keyof ActionInputs',
    '',
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(ACTION_INPUTS_FILE, renderActionInputs(inputSchemas))
}
